"""Install, describe, and remove the recurring run, per operating system.

Each install writes a small wrapper script into the data folder (paths baked in,
so the scheduler needs no environment of its own) and registers it:

    Windows  Task Scheduler task  (runs while you're logged in; wakes the PC; catches up if missed)
    macOS    launchd agent        ~/Library/LaunchAgents/
    Linux    systemd user timer   ~/.config/systemd/user/  (crontab line printed if systemd isn't there)

Only the Windows path has run in anger so far; macOS and Linux are written to the
platforms' documented formats and still need a first real install.
"""

from __future__ import annotations

import os
import shutil
import subprocess
import sys
from pathlib import Path

from . import app

DAYS = ["Sunday", "Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday"]
CADENCES = ("daily", "weekly", "biweekly")


def describe(sched: dict) -> str:
    c, day, time = sched["cadence"], sched.get("day", "Saturday"), sched["time"]
    return {"daily": f"every day at {time}",
            "weekly": f"every {day} at {time}",
            "biweekly": f"every other {day} at {time}"}[c]


def validate(sched: dict) -> None:
    if sched["cadence"] not in CADENCES:
        raise ValueError(f"cadence must be one of {', '.join(CADENCES)}")
    if sched["cadence"] != "daily" and sched.get("day") not in DAYS:
        raise ValueError(f"day must be one of {', '.join(DAYS)}")
    hh, mm = sched["time"].split(":")
    if not (0 <= int(hh) < 24 and 0 <= int(mm) < 60):
        raise ValueError("time must be HH:MM, 24-hour")


# ---------- wrapper scripts ----------

def _uv() -> str:
    return shutil.which("uv") or "uv"


def wrapper_ps1(home: Path, repo: Path, uv: str) -> str:
    return f"""# {app.APP_NAME} scheduled run. Generated by setup; safe to regenerate.
# Saved UTF-8 with BOM; console encoding set before any child process (Task Scheduler runs in the OEM code page).
[Console]::OutputEncoding = [System.Text.Encoding]::UTF8
$env:PYTHONIOENCODING = 'utf-8'
$env:{app.HOME_ENV} = '{home}'
$logDir = '{home / "work" / "logs"}'
New-Item -ItemType Directory -Force -Path $logDir | Out-Null
$log = Join-Path $logDir ((Get-Date -Format 'yyyy-MM-dd_HHmm') + '.log')
& '{uv}' run --project '{repo / "router"}' python -m jev_router.run @args *>&1 |
    ForEach-Object {{ "$_" }} | Out-File -FilePath $log -Encoding utf8
exit $LASTEXITCODE
"""


def wrapper_sh(home: Path, repo: Path, uv: str) -> str:
    return f"""#!/usr/bin/env bash
# {app.APP_NAME} scheduled run. Generated by setup; safe to regenerate.
export {app.HOME_ENV}="{home}"
export PATH="$PATH:/usr/local/bin:/opt/homebrew/bin:$HOME/.local/bin"
mkdir -p "{home}/work/logs"
log="{home}/work/logs/$(date +%Y-%m-%d_%H%M).log"
"{uv}" run --project "{repo}/router" python -m jev_router.run "$@" >"$log" 2>&1
"""


def write_wrapper(home: Path | None = None, repo: Path | None = None) -> Path:
    home, repo = home or app.home(), repo or app.REPO
    home.mkdir(parents=True, exist_ok=True)
    if sys.platform == "win32":
        path = home / "run.ps1"
        path.write_text(wrapper_ps1(home, repo, _uv()), encoding="utf-8-sig", newline="\r\n")
    else:
        path = home / "run.sh"
        path.write_text(wrapper_sh(home, repo, _uv()), encoding="utf-8")
        path.chmod(0o755)
    return path


# ---------- per-OS registration ----------

def windows_ps(sched: dict, wrapper: Path, task: str | None = None) -> str:
    task = task or app.task_name()
    hh, mm = sched["time"].split(":")
    at = f"{int(hh):02d}:{int(mm):02d}"
    trigger = (f"New-ScheduledTaskTrigger -Daily -At '{at}'" if sched["cadence"] == "daily" else
               f"New-ScheduledTaskTrigger -Weekly -WeeksInterval {2 if sched['cadence'] == 'biweekly' else 1} "
               f"-DaysOfWeek {sched['day']} -At '{at}'")
    return f"""
$action = New-ScheduledTaskAction -Execute 'powershell.exe' -Argument '-NoProfile -ExecutionPolicy Bypass -File "{wrapper}"' -WorkingDirectory '{wrapper.parent}'
$trigger = {trigger}
$settings = New-ScheduledTaskSettingsSet -StartWhenAvailable -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -WakeToRun -ExecutionTimeLimit (New-TimeSpan -Hours 4) -MultipleInstances IgnoreNew
$principal = New-ScheduledTaskPrincipal -UserId "$env:USERDOMAIN\\$env:USERNAME" -LogonType Interactive -RunLevel Limited
Register-ScheduledTask -TaskName '{task}' -Description 'X bookmarks to notes ({app.APP_NAME}). Data: {wrapper.parent}' -Action $action -Trigger $trigger -Settings $settings -Principal $principal -Force | Out-Null
"""


def launchd_plist(sched: dict, wrapper: Path, label: str) -> str:
    hh, mm = (int(x) for x in sched["time"].split(":"))
    day = "" if sched["cadence"] == "daily" else f"<key>Weekday</key><integer>{DAYS.index(sched['day'])}</integer>"
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key><string>{label}</string>
  <key>ProgramArguments</key><array><string>/bin/bash</string><string>{wrapper}</string></array>
  <key>StartCalendarInterval</key><dict>{day}<key>Hour</key><integer>{hh}</integer><key>Minute</key><integer>{mm}</integer></dict>
  <key>StandardErrorPath</key><string>{wrapper.parent}/work/logs/launchd.err</string>
</dict>
</plist>
"""


def systemd_units(sched: dict, wrapper: Path) -> tuple[str, str]:
    day = "" if sched["cadence"] == "daily" else sched["day"][:3] + " "
    service = f"""[Unit]
Description=X bookmarks to notes ({app.APP_NAME})

[Service]
Type=oneshot
ExecStart=/bin/bash {wrapper}
"""
    timer = f"""[Unit]
Description=Run {app.APP_NAME} on schedule

[Timer]
OnCalendar={day}*-*-* {sched['time']}:00
Persistent=true

[Install]
WantedBy=timers.target
"""
    return service, timer


def cron_line(sched: dict, wrapper: Path) -> str:
    hh, mm = (int(x) for x in sched["time"].split(":"))
    dow = "*" if sched["cadence"] == "daily" else str(DAYS.index(sched["day"]))
    return f"{mm} {hh} * * {dow} /bin/bash {wrapper}"


def install(cfg: dict) -> str:
    """Register the schedule for this OS. Returns a sentence saying what was done."""
    sched = cfg["schedule"]
    validate(sched)
    wrapper = write_wrapper()
    stem = app.task_name().lower()
    if sys.platform == "win32":
        p = subprocess.run(["powershell.exe", "-NoProfile", "-Command", windows_ps(sched, wrapper)],
                           capture_output=True, text=True)
        if p.returncode:
            raise RuntimeError(p.stderr.strip() or p.stdout.strip())
        return f"Task Scheduler task '{app.task_name()}' runs {describe(sched)}."
    if sys.platform == "darwin":
        label = f"com.{stem}"
        plist = Path.home() / "Library/LaunchAgents" / f"{label}.plist"
        plist.parent.mkdir(parents=True, exist_ok=True)
        plist.write_text(launchd_plist(sched, wrapper, label))
        uid = str(os.getuid())
        subprocess.run(["launchctl", "bootout", f"gui/{uid}", str(plist)], capture_output=True)
        subprocess.run(["launchctl", "bootstrap", f"gui/{uid}", str(plist)], check=True)
        return f"launchd agent '{label}' runs {describe(sched)} (if the Mac is asleep, it runs on wake)."
    if shutil.which("systemctl"):
        unit_dir = Path.home() / ".config/systemd/user"
        unit_dir.mkdir(parents=True, exist_ok=True)
        service, timer = systemd_units(sched, wrapper)
        (unit_dir / f"{stem}.service").write_text(service)
        (unit_dir / f"{stem}.timer").write_text(timer)
        subprocess.run(["systemctl", "--user", "daemon-reload"], check=True)
        subprocess.run(["systemctl", "--user", "enable", "--now", f"{stem}.timer"], check=True)
        return f"systemd user timer '{stem}.timer' runs {describe(sched)} (catches up if the machine was off)."
    return ("No systemd here. Add this line with 'crontab -e':\n    " + cron_line(sched, wrapper))


def installed() -> bool | None:
    """Is this install's schedule registered? None where it can't be told (a crontab line)."""
    stem = app.task_name().lower()
    if sys.platform == "win32":
        return subprocess.run(["schtasks", "/Query", "/TN", app.task_name()], capture_output=True).returncode == 0
    if sys.platform == "darwin":
        return (Path.home() / "Library/LaunchAgents" / f"com.{stem}.plist").exists()
    if shutil.which("systemctl"):
        return (Path.home() / ".config/systemd/user" / f"{stem}.timer").exists()
    return None


def scheduler_env() -> dict:
    """The environment a scheduled run starts with, as near as setup can tell: no venv from
    'uv run', no secrets or settings setup loaded into its own process, and on Windows the
    PATH rebuilt from the registry the way Task Scheduler builds it."""
    drop = {"VIRTUAL_ENV", "CLAUDE_BIN", "NOTES_BACKEND", "READER_PROFILE", "AUTH_TOKEN", "CT0", *app.SECRETS.values()}
    env = {k: v for k, v in os.environ.items() if k not in drop}
    venv = os.environ.get("VIRTUAL_ENV")
    paths = [p for p in env.get("PATH", "").split(os.pathsep) if not (venv and p.startswith(venv))]
    if sys.platform == "win32":
        try:
            import winreg
            parts = []
            for hive, key in [(winreg.HKEY_LOCAL_MACHINE, r"SYSTEM\CurrentControlSet\Control\Session Manager\Environment"),
                              (winreg.HKEY_CURRENT_USER, "Environment")]:
                with winreg.OpenKey(hive, key) as k:
                    try:
                        parts.append(os.path.expandvars(winreg.QueryValueEx(k, "Path")[0]))
                    except FileNotFoundError:
                        pass
            paths = os.pathsep.join(parts).split(os.pathsep)
        except OSError:
            pass
    env["PATH"] = os.pathsep.join(p for p in paths if p)
    return env


def run_now(args: list[str]) -> int:
    """Run the scheduled script itself, in a fresh shell, the way the scheduler would."""
    wrapper = write_wrapper()
    cmd = (["powershell.exe", "-NoProfile", "-ExecutionPolicy", "Bypass", "-File", str(wrapper), *args]
           if sys.platform == "win32" else ["/bin/bash", str(wrapper), *args])
    return subprocess.run(cmd, cwd=wrapper.parent, env=scheduler_env()).returncode


def remove() -> str:
    stem = app.task_name().lower()
    if sys.platform == "win32":
        subprocess.run(["powershell.exe", "-NoProfile", "-Command",
                        f"Unregister-ScheduledTask -TaskName '{app.task_name()}' -Confirm:$false"], capture_output=True)
        return f"Removed the Task Scheduler task '{app.task_name()}'."
    if sys.platform == "darwin":
        plist = Path.home() / "Library/LaunchAgents" / f"com.{stem}.plist"
        subprocess.run(["launchctl", "bootout", f"gui/{os.getuid()}", str(plist)], capture_output=True)
        plist.unlink(missing_ok=True)
        return "Removed the launchd agent."
    if shutil.which("systemctl"):
        subprocess.run(["systemctl", "--user", "disable", "--now", f"{stem}.timer"], capture_output=True)
        return "Disabled the systemd timer."
    return "Remove the crontab line by hand with 'crontab -e'."
